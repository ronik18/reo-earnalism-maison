-- Published content is immutable. Clone a revision to change it; retire visibility explicitly.
-- FOR SHARE serializes child writes with the revision state transition, using transaction locks.
CREATE FUNCTION maison_guard_revision_child() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE revision_id uuid; revision_state text;
BEGIN
    IF TG_OP = 'DELETE' THEN revision_id := OLD.edition_revision_id;
    ELSE revision_id := NEW.edition_revision_id; END IF;
    IF TG_OP = 'UPDATE' AND NEW.edition_revision_id <> OLD.edition_revision_id THEN
        RAISE EXCEPTION 'A content row cannot move between revisions' USING ERRCODE = '23514';
    END IF;
    SELECT state INTO revision_state FROM maison_edition_revision WHERE id = revision_id FOR SHARE;
    IF revision_state IS DISTINCT FROM 'draft' THEN
        RAISE EXCEPTION 'Content revision is frozen; clone it to edit' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER maison_anchor_mapping_frozen BEFORE INSERT OR UPDATE OR DELETE ON maison_anchor_mapping FOR EACH ROW EXECUTE FUNCTION maison_guard_revision_child();
