-- Draft revision 1.1.0: findings C01-C15 reconciled; local validation is not production acceptance.
-- NOT deployed. Run once on a fresh application DB AFTER Django auth/session migrations.
-- auth_user(id) and django_session(session_key) remain Django-owned; do not recreate them here.
-- allauth EmailAddress/SocialAccount remain identity authorities (see database-model.md).
-- App supplies UUID4 IDs and aware UTC timestamps. No UUID-generating extension required.
-- Translate to managed Django migrations with matching db_table names; do not run twice.
BEGIN;
SET LOCAL TIME ZONE 'UTC';
CREATE EXTENSION IF NOT EXISTS pg_trgm;
-- Custom Django User.email is normalized in the authentication adapter. Blank is migration-only.
CREATE UNIQUE INDEX maison_auth_user_email_normalized_uq ON auth_user(lower(email)) WHERE email <> '';

CREATE TABLE maison_member_profile (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES auth_user(id) ON DELETE RESTRICT,
    display_name varchar(100) NOT NULL DEFAULT '',
    locale varchar(2) NOT NULL DEFAULT 'en' CHECK (locale IN ('en','bn')),
    state varchar(16) NOT NULL DEFAULT 'active' CHECK (state IN ('active','suspended','deletion_pending','anonymised')),
    preferences jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(preferences) = 'object'),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE maison_member_role (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    role varchar(20) NOT NULL CHECK (role IN ('member','editor','rights_reviewer','publisher','support','admin')),
    granted_by uuid REFERENCES maison_member_profile(id) ON DELETE SET NULL,
    granted_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (member_id, role)
);
-- guest is an unauthenticated request context, never a persisted member role.
CREATE TABLE maison_device (
    id uuid PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    member_id uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    session_key varchar(40) UNIQUE REFERENCES django_session(session_key) ON DELETE SET NULL,
    token_binding_sha256 varchar(64) NOT NULL UNIQUE CHECK (token_binding_sha256 ~ '^[0-9a-f]{64}$'),
    label varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CHECK (expires_at > created_at),
    UNIQUE (id, member_id)
);
CREATE INDEX maison_device_member_active_idx ON maison_device(member_id, last_seen_at DESC) WHERE revoked_at IS NULL;
CREATE TABLE maison_email_action_token (
    id uuid PRIMARY KEY,
    member_id uuid REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    purpose varchar(20) NOT NULL CHECK (purpose IN ('verify_email','password_reset','magic_signin')),
    email_normalized varchar(254) NOT NULL,
    token_sha256 varchar(64) NOT NULL UNIQUE CHECK (token_sha256 ~ '^[0-9a-f]{64}$'),
    browser_binding_sha256 varchar(64) CHECK (browser_binding_sha256 ~ '^[0-9a-f]{64}$'),
    return_path varchar(512) NOT NULL DEFAULT '/' CHECK (return_path LIKE '/%' AND return_path NOT LIKE '//%'),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    failed_attempts smallint NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    CHECK (expires_at > created_at AND expires_at <= created_at +
        CASE purpose WHEN 'magic_signin' THEN interval '600 seconds'
                     WHEN 'password_reset' THEN interval '1800 seconds'
                     ELSE interval '86400 seconds' END),
    CHECK (consumed_at IS NULL OR consumed_at >= created_at)
);
CREATE INDEX maison_email_action_expiry_idx ON maison_email_action_token(expires_at);
CREATE TABLE maison_rate_limit_bucket (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_hash varchar(64) NOT NULL CHECK (bucket_hash ~ '^[0-9a-f]{64}$'),
    purpose varchar(32) NOT NULL,
    window_start timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    request_count integer NOT NULL CHECK (request_count >= 0),
    UNIQUE (bucket_hash, purpose, window_start),
    CHECK (expires_at > window_start)
);
CREATE INDEX maison_rate_limit_expiry_idx ON maison_rate_limit_bucket(expires_at);

CREATE TABLE maison_work (
    id uuid PRIMARY KEY,
    slug varchar(160) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    kind varchar(16) NOT NULL CHECK (kind IN ('book','series','course')),
    house varchar(20) NOT NULL CHECK (house IN ('classics','golpo','learn','interview','series','collections')),
    creator_display varchar(200) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    retired_at timestamptz
);
CREATE TABLE maison_slug_redirect (
    id uuid PRIMARY KEY,
    old_slug varchar(160) NOT NULL UNIQUE CHECK (old_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    work_id uuid NOT NULL REFERENCES maison_work(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE maison_edition (
    id uuid PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    work_id uuid NOT NULL REFERENCES maison_work(id) ON DELETE RESTRICT,
    locale varchar(2) NOT NULL CHECK (locale IN ('en','bn')),
    edition_number integer NOT NULL CHECK (edition_number > 0),
    paired_edition_id uuid REFERENCES maison_edition(id) ON DELETE SET NULL,
    live_revision_id uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (paired_edition_id IS NULL OR paired_edition_id <> id),
    UNIQUE (work_id, locale, edition_number)
);
CREATE TABLE maison_edition_revision (
    id uuid PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    edition_id uuid NOT NULL REFERENCES maison_edition(id) ON DELETE RESTRICT,
    revision_number integer NOT NULL CHECK (revision_number > 0),
    revision_sha256 varchar(64) NOT NULL CHECK (revision_sha256 ~ '^[0-9a-f]{64}$'),
    access_policy jsonb NOT NULL DEFAULT '{"reader":"deny","audio":"deny","video":"deny"}'::jsonb
      CHECK (jsonb_typeof(access_policy) = 'object' AND access_policy ?& ARRAY['reader','audio','video'] AND
             jsonb_typeof(access_policy->'reader') = 'string' AND jsonb_typeof(access_policy->'audio') = 'string' AND jsonb_typeof(access_policy->'video') = 'string' AND access_policy->>'reader' IN ('deny','free','paid') AND access_policy->>'audio' IN ('deny','free','paid') AND access_policy->>'video' IN ('deny','free','paid')),
    download_policy jsonb NOT NULL DEFAULT '{"reader":false,"audio":false,"video":false}'::jsonb
      CHECK (jsonb_typeof(download_policy) = 'object' AND download_policy ?& ARRAY['reader','audio','video'] AND
             jsonb_typeof(download_policy->'reader') = 'boolean' AND jsonb_typeof(download_policy->'audio') = 'boolean' AND jsonb_typeof(download_policy->'video') = 'boolean'),
    state varchar(12) NOT NULL DEFAULT 'draft' CHECK (state IN ('draft','ready','live','retired')),
    created_by uuid REFERENCES maison_member_profile(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    ready_at timestamptz,
    scheduled_at timestamptz,
    published_at timestamptz,
    retired_at timestamptz,
    CHECK (state = 'draft' OR ready_at IS NOT NULL),
    CHECK (state NOT IN ('live','retired') OR published_at IS NOT NULL),
    CHECK (state <> 'retired' OR retired_at IS NOT NULL),
    UNIQUE (edition_id, revision_number),
    UNIQUE (edition_id, revision_sha256),
    UNIQUE (id, edition_id)
);
CREATE UNIQUE INDEX maison_revision_one_live_idx ON maison_edition_revision(edition_id) WHERE state = 'live';
CREATE INDEX maison_revision_schedule_idx ON maison_edition_revision(scheduled_at) WHERE state = 'ready' AND scheduled_at IS NOT NULL;
ALTER TABLE maison_edition ADD CONSTRAINT maison_edition_live_revision_fk
    FOREIGN KEY (live_revision_id, id) REFERENCES maison_edition_revision(id, edition_id) DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX maison_edition_work_idx ON maison_edition(work_id);
CREATE TABLE maison_edition_metadata (
    id uuid PRIMARY KEY,
    edition_revision_id uuid NOT NULL REFERENCES maison_edition_revision(id) ON DELETE RESTRICT,
    locale varchar(2) NOT NULL CHECK (locale IN ('en','bn')),
    title varchar(300) NOT NULL,
    subtitle varchar(300) NOT NULL DEFAULT '',
    description text NOT NULL,
    creator_display varchar(200) NOT NULL,
    topic_keys text[] NOT NULL DEFAULT '{}',
    search_text text NOT NULL,
    search_document tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('simple'::regconfig, title), 'A') ||
        setweight(to_tsvector('simple'::regconfig, creator_display), 'B') ||
        setweight(to_tsvector('simple'::regconfig, search_text), 'C') ||
        setweight(to_tsvector('english'::regconfig, CASE WHEN locale = 'en' THEN search_text ELSE '' END), 'C')
    ) STORED,
    UNIQUE (edition_revision_id, locale)
);
CREATE INDEX maison_metadata_search_gin ON maison_edition_metadata USING gin(search_document);
CREATE INDEX maison_metadata_title_trgm ON maison_edition_metadata USING gin(lower(title) gin_trgm_ops);
CREATE INDEX maison_metadata_title_prefix ON maison_edition_metadata(lower(title) text_pattern_ops);
CREATE INDEX maison_metadata_topics_gin ON maison_edition_metadata USING gin(topic_keys);
CREATE TABLE maison_search_alias (
    id uuid PRIMARY KEY,
    locale varchar(2) NOT NULL CHECK (locale IN ('en','bn')),
    alias_normalized varchar(100) NOT NULL,
    target_normalized varchar(100) NOT NULL,
    reviewed_by uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE RESTRICT,
    reviewed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (locale, alias_normalized)
);
CREATE TABLE maison_unit (
    id uuid PRIMARY KEY,
    edition_revision_id uuid NOT NULL REFERENCES maison_edition_revision(id) ON DELETE RESTRICT,
    parent_unit_id uuid,
    kind varchar(16) NOT NULL CHECK (kind IN ('chapter','episode','lesson','section')),
    ordinal integer NOT NULL CHECK (ordinal > 0),
    label varchar(200) NOT NULL,
    is_preview boolean NOT NULL DEFAULT false,
    estimated_seconds integer CHECK (estimated_seconds >= 0),
    UNIQUE (edition_revision_id, ordinal),
    UNIQUE (id, edition_revision_id),
    FOREIGN KEY (parent_unit_id, edition_revision_id) REFERENCES maison_unit(id, edition_revision_id) ON DELETE RESTRICT,
    CHECK (parent_unit_id IS NULL OR parent_unit_id <> id)
);
CREATE TABLE maison_paragraph_anchor (
    id uuid PRIMARY KEY,
    edition_revision_id uuid NOT NULL,
    unit_id uuid NOT NULL,
    ordinal integer NOT NULL CHECK (ordinal > 0),
    kind varchar(16) NOT NULL CHECK (kind IN ('paragraph','stanza','heading','caption')),
    text_plain text NOT NULL,
    safe_html text NOT NULL,
    text_sha256 varchar(64) NOT NULL CHECK (text_sha256 ~ '^[0-9a-f]{64}$'),
    char_count integer GENERATED ALWAYS AS (char_length(text_plain)) STORED,
    FOREIGN KEY (unit_id, edition_revision_id) REFERENCES maison_unit(id, edition_revision_id) ON DELETE RESTRICT,
    UNIQUE (unit_id, ordinal),
    UNIQUE (id, unit_id, edition_revision_id)
);
CREATE INDEX maison_anchor_revision_idx ON maison_paragraph_anchor(edition_revision_id);
CREATE TABLE maison_anchor_mapping (
    id uuid PRIMARY KEY,
    edition_id uuid NOT NULL REFERENCES maison_edition(id) ON DELETE RESTRICT,
    source_revision_id uuid NOT NULL,
    source_unit_id uuid NOT NULL,
    source_anchor_id uuid NOT NULL,
    edition_revision_id uuid NOT NULL,
    target_unit_id uuid,
    target_anchor_id uuid,
    status varchar(12) NOT NULL CHECK (status IN ('verified','orphaned')),
    reviewed_by uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE RESTRICT,
    reviewed_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (source_revision_id, edition_id) REFERENCES maison_edition_revision(id, edition_id) ON DELETE RESTRICT,
    FOREIGN KEY (edition_revision_id, edition_id) REFERENCES maison_edition_revision(id, edition_id) ON DELETE RESTRICT,
    FOREIGN KEY (source_anchor_id, source_unit_id, source_revision_id) REFERENCES maison_paragraph_anchor(id, unit_id, edition_revision_id) ON DELETE RESTRICT,
    FOREIGN KEY (target_anchor_id, target_unit_id, edition_revision_id) REFERENCES maison_paragraph_anchor(id, unit_id, edition_revision_id) ON DELETE RESTRICT,
    CHECK (source_revision_id <> edition_revision_id),
    CHECK ((status = 'verified' AND target_unit_id IS NOT NULL AND target_anchor_id IS NOT NULL) OR
           (status = 'orphaned' AND target_unit_id IS NULL AND target_anchor_id IS NULL)),
    UNIQUE (source_anchor_id, edition_revision_id)
);
CREATE INDEX maison_anchor_mapping_target_idx ON maison_anchor_mapping(edition_revision_id);
CREATE TABLE maison_asset (
    id uuid PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    edition_revision_id uuid NOT NULL REFERENCES maison_edition_revision(id) ON DELETE RESTRICT,
    unit_id uuid,
    kind varchar(24) NOT NULL CHECK (kind IN ('reader_package','preview_reader_package','audio_chapter','preview_audio','video','caption','transcript','cover','reader_source','timing_map','rights_document')),
    format varchar(8) NOT NULL CHECK (format IN ('reader','audio','video')),
    locale varchar(2) NOT NULL CHECK (locale IN ('en','bn')),
    provider varchar(8) NOT NULL CHECK (provider IN ('r2','stream')),
    private_object_key text NOT NULL,
    visibility varchar(16) NOT NULL CHECK (visibility IN ('private','public_preview','public_cover')),
    state varchar(12) NOT NULL CHECK (state IN ('uploading','processing','ready','failed')),
    sha256 varchar(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    bytes bigint NOT NULL CHECK (bytes >= 0),
    mime_type varchar(100) NOT NULL,
    duration_ms bigint CHECK (duration_ms > 0),
    variant varchar(32) NOT NULL DEFAULT 'default',
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (unit_id, edition_revision_id) REFERENCES maison_unit(id, edition_revision_id) ON DELETE RESTRICT,
    UNIQUE (provider, private_object_key),
    UNIQUE (id, edition_revision_id),
    UNIQUE (id, edition_revision_id, format),
    CHECK (provider <> 'stream' OR (kind = 'video' AND format = 'video')),
    CHECK (visibility = 'private' OR kind IN ('cover','preview_reader_package','preview_audio')),
    CHECK (kind NOT IN ('reader_source','timing_map','rights_document') OR visibility = 'private'),
    CHECK (kind NOT IN ('reader_package','audio_chapter','video') OR visibility = 'private'),
    CHECK (kind NOT IN ('audio_chapter','preview_audio','video') OR duration_ms IS NOT NULL)
);
CREATE INDEX maison_asset_revision_kind_idx ON maison_asset(edition_revision_id, kind, state);
CREATE INDEX maison_asset_unit_idx ON maison_asset(unit_id) WHERE unit_id IS NOT NULL;
CREATE TABLE maison_rights_record (
    id uuid PRIMARY KEY,
    edition_revision_id uuid NOT NULL REFERENCES maison_edition_revision(id) ON DELETE RESTRICT,
    format varchar(8) NOT NULL CHECK (format IN ('reader','audio','video')),
    state varchar(12) NOT NULL CHECK (state IN ('pending','approved','revoked')),
    commercial_use boolean NOT NULL DEFAULT false,
    allow_download boolean NOT NULL DEFAULT false,
    territories text[] NOT NULL,
    valid_from timestamptz NOT NULL,
    valid_until timestamptz,
    private_evidence_key text NOT NULL,
    evidence_sha256 varchar(64) NOT NULL CHECK (evidence_sha256 ~ '^[0-9a-f]{64}$'),
    reviewer_id uuid REFERENCES maison_member_profile(id) ON DELETE RESTRICT,
    reviewed_at timestamptz,
    revoked_at timestamptz,
    CHECK (cardinality(territories) > 0),
    CHECK (valid_until IS NULL OR valid_until > valid_from),
    CHECK (state <> 'approved' OR (commercial_use AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL)),
    CHECK (state <> 'revoked' OR revoked_at IS NOT NULL),
    CHECK (format <> 'video' OR NOT allow_download),
    UNIQUE (edition_revision_id, format),
    UNIQUE (id, edition_revision_id, format)
);
CREATE TABLE maison_publication_check (
    id uuid PRIMARY KEY,
    edition_revision_id uuid NOT NULL REFERENCES maison_edition_revision(id) ON DELETE RESTRICT,
    check_name varchar(16) NOT NULL CHECK (check_name IN ('rights','content','assets','metadata','browser')),
    revision_sha256 varchar(64) NOT NULL CHECK (revision_sha256 ~ '^[0-9a-f]{64}$'),
    passed boolean NOT NULL,
    evidence_ref text NOT NULL,
    checked_by uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE RESTRICT,
    checked_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (edition_revision_id, check_name)
);
CREATE TABLE maison_timing_map (
    id uuid PRIMARY KEY,
    edition_revision_id uuid NOT NULL,
    unit_id uuid NOT NULL,
    audio_asset_id uuid NOT NULL,
    text_revision_sha256 varchar(64) NOT NULL CHECK (text_revision_sha256 ~ '^[0-9a-f]{64}$'),
    audio_sha256 varchar(64) NOT NULL CHECK (audio_sha256 ~ '^[0-9a-f]{64}$'),
    granularity varchar(12) NOT NULL CHECK (granularity IN ('paragraph','sentence','word')),
    state varchar(16) NOT NULL CHECK (state IN ('draft','human_verified','rejected')),
    verified_by uuid REFERENCES maison_member_profile(id) ON DELETE RESTRICT,
    verified_at timestamptz,
    FOREIGN KEY (unit_id, edition_revision_id) REFERENCES maison_unit(id, edition_revision_id) ON DELETE RESTRICT,
    FOREIGN KEY (audio_asset_id, edition_revision_id) REFERENCES maison_asset(id, edition_revision_id) ON DELETE RESTRICT,
    CHECK (state <> 'human_verified' OR (verified_by IS NOT NULL AND verified_at IS NOT NULL)),
    UNIQUE (audio_asset_id, text_revision_sha256),
    UNIQUE (id, unit_id, edition_revision_id)
);
CREATE INDEX maison_timing_revision_idx ON maison_timing_map(edition_revision_id);
CREATE TABLE maison_timing_segment (
    id uuid PRIMARY KEY,
    timing_map_id uuid NOT NULL,
    edition_revision_id uuid NOT NULL,
    unit_id uuid NOT NULL,
    anchor_id uuid NOT NULL,
    ordinal integer NOT NULL CHECK (ordinal > 0),
    char_start integer NOT NULL CHECK (char_start >= 0),
    char_end integer NOT NULL CHECK (char_end > char_start),
    start_ms bigint NOT NULL CHECK (start_ms >= 0),
    end_ms bigint NOT NULL CHECK (end_ms > start_ms),
    FOREIGN KEY (timing_map_id, unit_id, edition_revision_id) REFERENCES maison_timing_map(id, unit_id, edition_revision_id) ON DELETE RESTRICT,
    FOREIGN KEY (anchor_id, unit_id, edition_revision_id) REFERENCES maison_paragraph_anchor(id, unit_id, edition_revision_id) ON DELETE RESTRICT,
    UNIQUE (timing_map_id, ordinal)
);
CREATE INDEX maison_timing_seek_idx ON maison_timing_segment(timing_map_id, start_ms);
CREATE TABLE maison_catalog_collection (
    id uuid PRIMARY KEY,
    slug varchar(160) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    title_en varchar(200) NOT NULL,
    title_bn varchar(200) NOT NULL,
    house varchar(20) NOT NULL CHECK (house IN ('classics','golpo','learn','interview','series','collections')),
    published boolean NOT NULL DEFAULT false,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE maison_catalog_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id uuid NOT NULL REFERENCES maison_catalog_collection(id) ON DELETE CASCADE,
    edition_id uuid NOT NULL REFERENCES maison_edition(id) ON DELETE RESTRICT,
    sort_order integer NOT NULL CHECK (sort_order >= 0),
    UNIQUE (collection_id, edition_id),
    UNIQUE (collection_id, sort_order) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX maison_catalog_item_edition_idx ON maison_catalog_item(edition_id);

CREATE TABLE maison_progress (
    id uuid PRIMARY KEY,
    member_id uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    edition_id uuid NOT NULL REFERENCES maison_edition(id) ON DELETE RESTRICT,
    edition_revision_id uuid NOT NULL,
    format varchar(8) NOT NULL CHECK (format IN ('reader','audio','video')),
    unit_id uuid NOT NULL,
    anchor_id uuid,
    offset_chars integer CHECK (offset_chars >= 0),
    position_ms bigint CHECK (position_ms >= 0),
    fraction_complete numeric(7,6) NOT NULL CHECK (fraction_complete BETWEEN 0 AND 1),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    last_operation_id uuid NOT NULL,
    client_occurred_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (edition_revision_id, edition_id) REFERENCES maison_edition_revision(id, edition_id) ON DELETE RESTRICT,
    FOREIGN KEY (unit_id, edition_revision_id) REFERENCES maison_unit(id, edition_revision_id) ON DELETE RESTRICT,
    FOREIGN KEY (anchor_id, unit_id, edition_revision_id) REFERENCES maison_paragraph_anchor(id, unit_id, edition_revision_id) ON DELETE RESTRICT,
    CHECK ((format = 'reader' AND anchor_id IS NOT NULL AND offset_chars IS NOT NULL) OR (format IN ('audio','video') AND position_ms IS NOT NULL)),
    UNIQUE (member_id, edition_id, format)
);
CREATE INDEX maison_progress_continue_idx ON maison_progress(member_id, updated_at DESC, id);
CREATE INDEX maison_progress_revision_idx ON maison_progress(edition_revision_id);

-- Explicit completion is independent of a seek position. Absent state is API version0.
CREATE TABLE maison_completion (
    id uuid PRIMARY KEY,
    member_id uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    edition_id uuid NOT NULL REFERENCES maison_edition(id) ON DELETE RESTRICT,
    edition_revision_id uuid NOT NULL,
    format varchar(8) NOT NULL CHECK (format IN ('reader','audio','video')),
    is_complete boolean NOT NULL DEFAULT false,
    completed_at timestamptz,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    last_operation_id uuid NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (edition_revision_id, edition_id) REFERENCES maison_edition_revision(id, edition_id) ON DELETE RESTRICT,
    CHECK ((is_complete AND completed_at IS NOT NULL) OR (NOT is_complete AND completed_at IS NULL)),
    UNIQUE (member_id, edition_id, format)
);
CREATE INDEX maison_completion_finished_idx ON maison_completion(member_id, completed_at DESC) WHERE is_complete;

CREATE TABLE maison_operation_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    operation_id uuid NOT NULL,
    resource_kind varchar(20) NOT NULL CHECK (resource_kind IN ('progress','annotation','saved_item','personal_list','quiz_attempt','lesson_progress','completion','download_license','asset_upload','asset_complete','publication_action','device_action','account_action','privacy_request','contact_request')),
    resource_id uuid NOT NULL,
    request_sha256 varchar(64) NOT NULL CHECK (request_sha256 ~ '^[0-9a-f]{64}$'),
    resulting_version bigint NOT NULL CHECK (resulting_version > 0),
    http_status smallint NOT NULL CHECK (http_status BETWEEN 200 AND 299),
    response_snapshot jsonb NOT NULL CHECK (jsonb_typeof(response_snapshot) = 'object'),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    UNIQUE (member_id, operation_id),
    CHECK (expires_at = created_at + interval '35 days')
);
CREATE INDEX maison_operation_expiry_idx ON maison_operation_receipt(expires_at);
CREATE TABLE maison_annotation (
    id uuid PRIMARY KEY,
    member_id uuid NOT NULL REFERENCES maison_member_profile(id) ON DELETE CASCADE,
    edition_revision_id uuid NOT NULL,
    unit_id uuid NOT NULL,
    anchor_id uuid NOT NULL,
    end_anchor_id uuid,
    start_offset integer NOT NULL CHECK (start_offset >= 0),
    end_offset integer CHECK (end_offset >= 0),
    kind varchar(12) NOT NULL CHECK (kind IN ('bookmark','highlight','note')),
    color varchar(12) CHECK (color IN ('gold','mint','rose','lavender')),
    quoted_text_truncated boolean NOT NULL DEFAULT false,
    quoted_text text CHECK (char_length(quoted_text) <= 2048 AND octet_length(quoted_text) <= 8192),
    note text CHECK (octet_length(note) <= 8192),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
