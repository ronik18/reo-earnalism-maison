CREATE FUNCTION maison_guard_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'draft' THEN RAISE EXCEPTION 'Revision starts as draft' USING ERRCODE = '23514'; END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        IF OLD.state <> 'draft' THEN RAISE EXCEPTION 'Frozen revision cannot be deleted' USING ERRCODE = '23514'; END IF;
        RETURN OLD;
    END IF;
    IF NEW.edition_id <> OLD.edition_id OR NEW.revision_number <> OLD.revision_number OR
       (OLD.state <> 'draft' AND NEW.revision_sha256 <> OLD.revision_sha256) THEN
        RAISE EXCEPTION 'Revision identity is immutable' USING ERRCODE = '23514';
    END IF;
    IF NEW.state <> OLD.state AND NOT ((OLD.state = 'draft' AND NEW.state = 'ready') OR
       (OLD.state = 'ready' AND NEW.state = 'live') OR (OLD.state = 'live' AND NEW.state = 'retired')) THEN
        RAISE EXCEPTION 'Invalid publication transition' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER maison_revision_guard BEFORE INSERT OR UPDATE OR DELETE ON maison_edition_revision FOR EACH ROW EXECUTE FUNCTION maison_guard_revision();

-- Cross-row download bounds cannot be expressed in CHECK constraints.
CREATE FUNCTION maison_guard_download_license() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE e maison_entitlement%ROWTYPE; r maison_rights_record%ROWTYPE; d maison_device%ROWTYPE; edition_uuid uuid;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF (to_jsonb(NEW) - 'revoked_at') IS DISTINCT FROM (to_jsonb(OLD) - 'revoked_at') OR
           NEW.revoked_at IS NULL OR OLD.revoked_at IS NOT NULL THEN
            RAISE EXCEPTION 'License is immutable except first revocation; issue a fresh grant' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    SELECT * INTO STRICT e FROM maison_entitlement WHERE id = NEW.entitlement_id FOR SHARE;
    SELECT * INTO STRICT r FROM maison_rights_record WHERE id = NEW.rights_record_id FOR SHARE;
    SELECT * INTO STRICT d FROM maison_device WHERE id = NEW.device_id FOR SHARE;
    SELECT edition_id INTO STRICT edition_uuid FROM maison_edition_revision WHERE id = NEW.edition_revision_id;
    IF e.member_id <> NEW.member_id OR d.member_id <> NEW.member_id OR e.revoked_at IS NOT NULL OR
       d.revoked_at IS NOT NULL OR d.expires_at < NEW.expires_at OR
       NEW.issued_at < e.valid_from OR NEW.expires_at > e.valid_until OR NOT (NEW.format = ANY(e.formats)) OR
       r.state <> 'approved' OR NOT r.allow_download OR NOT r.commercial_use OR
       NEW.issued_at < r.valid_from OR (r.valid_until IS NOT NULL AND NEW.expires_at > r.valid_until) OR
       (e.scope = 'edition' AND e.edition_id <> edition_uuid) OR
       (e.scope = 'track' AND NOT EXISTS (SELECT 1 FROM maison_lesson l WHERE l.track_id = e.track_id AND l.edition_revision_id = NEW.edition_revision_id)) THEN
        RAISE EXCEPTION 'Download exceeds current entitlement, device or rights' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER maison_download_guard BEFORE INSERT OR UPDATE ON maison_download_license FOR EACH ROW EXECUTE FUNCTION maison_guard_download_license();

