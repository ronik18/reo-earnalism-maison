-- Serialize financial aggregates on their parent rows. Never call a provider inside these locks.
CREATE FUNCTION maison_guard_payment() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE o maison_order%ROWTYPE;
BEGIN
    SELECT * INTO STRICT o FROM maison_order WHERE id = NEW.order_id FOR SHARE;
    IF NEW.currency <> o.currency OR NEW.amount_minor <> o.total_minor OR NEW.provider <> o.provider THEN
        RAISE EXCEPTION 'Payment does not match server-owned order' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND (NEW.order_id, NEW.provider, NEW.provider_payment_id, NEW.currency, NEW.amount_minor)
       IS DISTINCT FROM (OLD.order_id, OLD.provider, OLD.provider_payment_id, OLD.currency, OLD.amount_minor) THEN
        RAISE EXCEPTION 'Payment identity and amounts are immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER maison_payment_guard BEFORE INSERT OR UPDATE ON maison_payment FOR EACH ROW EXECUTE FUNCTION maison_guard_payment();
CREATE FUNCTION maison_guard_refund() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p maison_payment%ROWTYPE; reserved bigint;
BEGIN
    SELECT * INTO STRICT p FROM maison_payment WHERE id = NEW.payment_id FOR UPDATE;
    IF NEW.currency <> p.currency OR NEW.provider <> p.provider OR p.captured_at IS NULL THEN
        RAISE EXCEPTION 'Refund must match captured payment' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.status = 'processed' AND NEW.status <> 'processed' THEN
        RAISE EXCEPTION 'Processed refund cannot be downgraded' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND (NEW.payment_id, NEW.currency, NEW.idempotency_key)
       IS DISTINCT FROM (OLD.payment_id, OLD.currency, OLD.idempotency_key) THEN
        RAISE EXCEPTION 'Refund identity is immutable' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.amount_minor IS DISTINCT FROM OLD.amount_minor AND
       NOT (OLD.status = 'requested' AND NEW.status = 'approved' AND NEW.amount_minor <= OLD.amount_minor) THEN
        RAISE EXCEPTION 'Refund amount changes only once at bounded approval' USING ERRCODE = '23514';
    END IF;
    SELECT coalesce(sum(amount_minor),0) INTO reserved FROM maison_refund
      WHERE payment_id = p.id AND id <> NEW.id AND status IN ('requested','approved','submitted','pending','processed');
    IF NEW.status NOT IN ('failed','rejected') AND reserved + NEW.amount_minor > p.amount_minor THEN
        RAISE EXCEPTION 'Refund exceeds unreserved captured amount' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER maison_refund_guard BEFORE INSERT OR UPDATE ON maison_refund FOR EACH ROW EXECUTE FUNCTION maison_guard_refund();
CREATE FUNCTION maison_guard_allocation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p maison_payment%ROWTYPE; r maison_invoice_revision%ROWTYPE; i maison_invoice%ROWTYPE; allocated bigint;
BEGIN
    SELECT * INTO STRICT p FROM maison_payment WHERE id = NEW.payment_id FOR UPDATE;
    SELECT * INTO STRICT r FROM maison_invoice_revision WHERE id = NEW.invoice_revision_id;
    SELECT * INTO STRICT i FROM maison_invoice WHERE id = r.invoice_id FOR UPDATE;
    IF p.order_id <> i.order_id OR NEW.currency <> p.currency OR NEW.currency <> r.currency OR
       r.document_kind <> 'invoice' OR p.captured_at IS NULL THEN
        RAISE EXCEPTION 'Allocation does not match captured payment and invoice' USING ERRCODE = '23514';
    END IF;
    SELECT coalesce(sum(amount_minor),0) INTO allocated FROM maison_payment_allocation WHERE payment_id = p.id;
    IF allocated + NEW.amount_minor > p.amount_minor THEN
        RAISE EXCEPTION 'Payment overallocated' USING ERRCODE = '23514';
    END IF;
    SELECT coalesce(sum(a.amount_minor),0) INTO allocated FROM maison_payment_allocation a
      JOIN maison_invoice_revision ir ON ir.id = a.invoice_revision_id WHERE ir.invoice_id = i.id;
    IF allocated + NEW.amount_minor > r.total_minor THEN
        RAISE EXCEPTION 'Invoice overallocated' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER maison_allocation_guard BEFORE INSERT ON maison_payment_allocation FOR EACH ROW EXECUTE FUNCTION maison_guard_allocation();

